// Regenerates vendor/retire-js-dataset.js from the upstream Retire.js
// repository, so vulnerable-library detection doesn't silently age.
//
//   npm run update:retire            # refresh the libraries already vendored + EXTRA_LIBRARIES
//   npm run update:retire -- --check # exit 1 if the vendored data is older than STALE_DAYS (for CI)
//
// Same trimming as the original hand-vendored file (see its header): only
// `uri`/`filename`/`filecontent` extractors (the kinds retire-js-scan.js can evaluate
// without running page JS), and per vulnerability only severity, version
// bounds, a <=200-char summary and the first info link. Regexes and version
// bounds are copied verbatim. The extension must bundle this data (Manifest
// V3 forbids loading remote code or data-as-code at runtime), which is why
// it is regenerated here rather than fetched by the extension.

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "https://raw.githubusercontent.com/RetireJS/retire.js/master/repository/jsrepository.json";
const OUT = new URL("../vendor/retire-js-dataset.js", import.meta.url);
const STALE_DAYS = 120; // keep in sync with LIBRARY_DATA_STALE_DAYS in backend/src/services/site-security/index.js

// Commonly seen front-end libraries beyond the original 16. Names that don't
// exist upstream (or ship no uri/filename/filecontent extractor) are skipped with a
// warning rather than failing the update.
const EXTRA_LIBRARIES = ["underscore.js", "dojo", "DOMPurify", "vue", "react", "axios", "select2", "jquery-validation", "tinymce", "ckeditor", "highcharts", "video.js", "bootstrap-select", "jquery.prettyPhoto"];

function currentMeta() {
  const src = readFileSync(OUT, "utf8");
  const fetched = /fetchedAt:\s*"([^"]+)"/.exec(src)?.[1] ?? null;
  const keys = [...src.matchAll(/^ {2}"([^"]+)": \{\r?$/gm)].map((m) => m[1]);
  return { fetched, keys };
}

if (process.argv.includes("--check")) {
  const { fetched } = currentMeta();
  const age = fetched ? Math.floor((Date.now() - Date.parse(fetched)) / 86_400_000) : Infinity;
  console.log(`vendored Retire.js data fetched ${fetched ?? "(unknown)"} - ${age} day(s) old`);
  process.exit(age > STALE_DAYS ? 1 : 0);
}

function trimVulnerability(v) {
  const out = { severity: v.severity };
  if (v.below) out.below = v.below;
  if (v.atOrAbove) out.atOrAbove = v.atOrAbove;
  const summary = v.identifiers?.summary ?? (v.identifiers?.CVE?.[0] ? `${v.identifiers.CVE[0]}` : "Known vulnerability");
  out.summary = String(summary).slice(0, 200);
  if (Array.isArray(v.info) && v.info[0]) out.info = v.info[0];
  return out;
}

function trimLibrary(name, lib) {
  const extractors = {};
  if (lib.extractors?.uri?.length) extractors.uri = lib.extractors.uri;
  if (lib.extractors?.filename?.length) extractors.filename = lib.extractors.filename;
  if (lib.extractors?.filecontent?.length) extractors.filecontent = lib.extractors.filecontent;
  if (!extractors.uri && !extractors.filename && !extractors.filecontent) return null;
  return {
    npmname: lib.npmname || name,
    extractors,
    vulnerabilities: (lib.vulnerabilities ?? []).filter((v) => v.below || v.atOrAbove).map(trimVulnerability),
  };
}

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`failed to fetch ${SOURCE}: HTTP ${res.status}`);
const upstream = await res.json();

const { keys } = currentMeta();
const wanted = [...new Set([...keys, ...EXTRA_LIBRARIES])];
const dataset = {};
for (const name of wanted) {
  if (!upstream[name]) {
    console.warn(`skip ${name}: not in upstream repository`);
    continue;
  }
  const trimmed = trimLibrary(name, upstream[name]);
  if (!trimmed) {
    console.warn(`skip ${name}: no uri/filename/filecontent extractors (func/hash-only upstream)`);
    continue;
  }
  dataset[name] = trimmed;
}

const fetchedAt = new Date().toISOString().slice(0, 10);
// Keep the file ASCII: the §§version§§ placeholder is written as a \u00a7 escape.
const body = JSON.stringify(dataset, null, 2).replace(/§/g, "\\u00a7");
const libraryList = Object.keys(dataset).join(", ");

writeFileSync(
  OUT,
  `// Trimmed subset of the Retire.js JS-library vulnerability signatures.
//
// GENERATED by extension/scripts/update-retire-dataset.mjs - do not edit by
// hand; rerun \`npm run update:retire\` in extension/ to refresh.
//
// Source: https://github.com/RetireJS/retire.js/blob/master/repository/jsrepository.json
// License: Apache License 2.0 (https://github.com/RetireJS/retire.js/blob/master/LICENSE.txt)
// Fetched: ${fetchedAt}. ${Object.keys(dataset).length} libraries: ${libraryList}.
// Each library keeps only its \`uri\`/\`filename\`/\`filecontent\` extractor regexes and a
// trimmed \`vulnerabilities\` array (severity, version bounds, one summary, one
// info link). Every regex and version boundary is copied verbatim from upstream.
//
// \`§§version§§\` inside each regex is retire.js's own placeholder for the
// version-number capture group - retire-js-scan.js substitutes it with a real
// capturing group before compiling, exactly as upstream retire.js does.

export const RETIRE_JS_DATASET_META = { source: "retire.js jsrepository.json", fetchedAt: "${fetchedAt}", libraries: ${Object.keys(dataset).length} };

export const RETIRE_JS_DATASET = ${body};
`
);
console.log(`wrote ${Object.keys(dataset).length} libraries to vendor/retire-js-dataset.js (fetched ${fetchedAt})`);
